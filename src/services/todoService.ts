import { StoreStorage } from './storeStorage';
import { StoreService } from './storeService';

export interface StoreTask {
  id: string;
  title: string;
  category: 'schedule' | 'labor_law' | 'tplh' | 'admin' | 'custom';
  priority: 'high' | 'medium' | 'low';
  completed: boolean;
  dueDate?: string;
  actionModule?: 'managers_schedule' | 'labor_forecast' | 'trainings' | 'col_calculator';
  actionLabel?: string;
  isAutoGenerated?: boolean;
  createdAt: string;
}

class TodoService {
  private tasks: StoreTask[] = [];
  private listeners: Array<() => void> = [];
  private currentStoreId: string = '';

  constructor() {
    this.currentStoreId = (typeof window !== 'undefined' ? StoreService.getCurrentStore()?.id : '') || '108120';
    this.loadTasks();
    if (this.tasks.length === 0) {
      this.initDefaultTasks();
    }

    if (typeof window !== 'undefined') {
      window.addEventListener('sbx:store-switched', (e: any) => {
        const newStoreId = e?.detail?.currentStore?.id || e?.detail?.id;
        if (newStoreId && newStoreId !== this.currentStoreId) {
          this.switchStore(newStoreId);
        }
      });
      window.addEventListener('sbx-store-changed', (e: any) => {
        const newStoreId = e?.detail?.id;
        if (newStoreId && newStoreId !== this.currentStoreId) {
          this.switchStore(newStoreId);
        }
      });
    }
  }

  public switchStore(newStoreId: string) {
    this.currentStoreId = newStoreId;
    this.loadTasks();
    if (this.tasks.length === 0) {
      this.initDefaultTasks();
    }
    this.notify();
  }

  public subscribe(listener: () => void): () => void {
    this.listeners.push(listener);
    return () => {
      this.listeners = this.listeners.filter((l) => l !== listener);
    };
  }

  private notify() {
    this.listeners.forEach((l) => {
      try {
        l();
      } catch (e) {
        console.error('Błąd listenera todo:', e);
      }
    });
  }

  private loadTasks() {
    try {
      this.tasks = StoreStorage.getItem<StoreTask[]>('todos', this.currentStoreId) || [];
    } catch {
      this.tasks = [];
    }
  }

  private saveTasks() {
    try {
      StoreStorage.setItem('todos', this.tasks, this.currentStoreId);
    } catch {}
    this.notify();
  }

  public initDefaultTasks() {
    this.tasks = [
      {
        id: 'task_pub_month',
        title: 'Opublikuj i zamroź grafik na kolejny miesiąc (art. 129 § 3 KP)',
        category: 'schedule',
        priority: 'high',
        completed: false,
        dueDate: '7 dni przed startem okresu',
        actionModule: 'managers_schedule',
        actionLabel: 'Otwórz Grafik',
        isAutoGenerated: true,
        createdAt: new Date().toISOString(),
      },
      {
        id: 'task_kp_rest',
        title: 'Zweryfikuj odpoczynki 11h w grafiku menedżerskim (Tarcza KP)',
        category: 'labor_law',
        priority: 'high',
        completed: false,
        dueDate: 'Przed publikacją',
        actionModule: 'managers_schedule',
        actionLabel: 'Sprawdź Naruszenia',
        isAutoGenerated: true,
        createdAt: new Date().toISOString(),
      },
      {
        id: 'task_w2_planning',
        title: 'Zaplanuj pulę godzin HANW dla tygodnia docelowego W+2',
        category: 'tplh',
        priority: 'medium',
        completed: false,
        dueDate: 'W każdy poniedziałek do 18:00',
        actionModule: 'labor_forecast',
        actionLabel: 'Labor Balancing',
        isAutoGenerated: true,
        createdAt: new Date().toISOString(),
      },
      {
        id: 'task_mapal_import',
        title: 'Zaimportuj raport MAPAL Fichajes z ewidencją czasu pracy',
        category: 'admin',
        priority: 'medium',
        completed: true,
        dueDate: 'Po zakończeniu tygodnia',
        actionModule: 'managers_schedule',
        actionLabel: 'Ewidencja RCP',
        isAutoGenerated: true,
        createdAt: new Date().toISOString(),
      },
    ];
    this.saveTasks();
  }

  public getTasks(): StoreTask[] {
    return [...this.tasks];
  }

  public getPendingCount(): number {
    return this.tasks.filter((t) => !t.completed).length;
  }

  public getHighPriorityCount(): number {
    return this.tasks.filter((t) => !t.completed && t.priority === 'high').length;
  }

  public toggleTask(id: string) {
    this.tasks = this.tasks.map((t) =>
      t.id === id ? { ...t, completed: !t.completed } : t
    );
    this.saveTasks();
  }

  public addTask(title: string, priority: 'high' | 'medium' | 'low' = 'medium') {
    const newTask: StoreTask = {
      id: `task_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      title: title.trim(),
      category: 'custom',
      priority,
      completed: false,
      isAutoGenerated: false,
      createdAt: new Date().toISOString(),
    };
    this.tasks = [newTask, ...this.tasks];
    this.saveTasks();
    return newTask;
  }

  public deleteTask(id: string) {
    this.tasks = this.tasks.filter((t) => t.id !== id);
    this.saveTasks();
  }

  public resetTasks() {
    this.initDefaultTasks();
  }

  public syncBackupOverdueTask(isOverdue: boolean, days?: number) {
    const taskId = 'task_db_backup_overdue';
    const existingIndex = this.tasks.findIndex((t) => t.id === taskId);
    if (isOverdue) {
      const title = days !== undefined
        ? `Wykonaj kopię zapasową bazy SQLite (od ostatniej minęło ${days} dni)`
        : 'Wykonaj pierwszą kopię zapasową bazy SQLite (brak kopii)';
      if (existingIndex >= 0) {
        if (this.tasks[existingIndex].title !== title || this.tasks[existingIndex].completed) {
          this.tasks[existingIndex].title = title;
          this.tasks[existingIndex].completed = false;
          this.saveTasks();
        }
      } else {
        this.tasks.unshift({
          id: taskId,
          title,
          category: 'admin',
          priority: 'high',
          completed: false,
          dueDate: 'Zalecane natychmiast',
          actionLabel: 'Kopia SQLite',
          isAutoGenerated: true,
          createdAt: new Date().toISOString(),
        });
        this.saveTasks();
      }
    } else {
      if (existingIndex >= 0 && !this.tasks[existingIndex].completed) {
        this.tasks[existingIndex].completed = true;
        this.saveTasks();
      }
    }
  }
}

export const todoService = new TodoService();
